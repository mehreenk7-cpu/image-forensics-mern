
import { useEffect, useState } from "react";
import api from "../api/client";
import "./Reports.css";

type CaseRecord = {
  _id: string;
  caseNumber?: string;
  title?: string;
  description?: string;
  status?: string;
  priority?: string;
  createdAt?: string;
};

function Reports() {
  const [cases, setCases] = useState<CaseRecord[]>([]);
  const [selectedCase, setSelectedCase] = useState("");
  const [reportType, setReportType] = useState(
    "Complete Investigation Report"
  );
  const [investigator, setInvestigator] = useState("");
  const [notes, setNotes] = useState("");
  const [preview, setPreview] = useState("");
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const [message, setMessage] = useState("");
  const [messageType, setMessageType] = useState<"success" | "error">(
    "success"
  );

  useEffect(() => {
    const loadCases = async () => {
      try {
        const token = localStorage.getItem("forensics_token");

        const response = await api.get("/cases", {
          headers: {
            Authorization: `Bearer ${token}`,
          },
        });

        const data = response.data;

        const caseList: CaseRecord[] = Array.isArray(data)
          ? data
          : data.cases || data.data || [];

        setCases(caseList);

        if (caseList.length > 0) {
          setSelectedCase(caseList[0]._id);
        }
      } catch (error) {
        console.error("Unable to load cases:", error);
        setMessageType("error");
        setMessage("Unable to load investigation cases.");
      } finally {
        setLoading(false);
      }
    };

    loadCases();
  }, []);

  const currentCase = cases.find(
    (item) => item._id === selectedCase
  );

  const showMessage = (
    text: string,
    type: "success" | "error" = "success"
  ) => {
    setMessage(text);
    setMessageType(type);
  };

  const generateReport = () => {
    if (!currentCase) {
      showMessage("Please select an investigation case.", "error");
      return;
    }

    setGenerating(true);
    setMessage("");

    const report = `
IMAGE FORENSICS AND LOG ANALYSER
INVESTIGATION REPORT
========================================

REPORT TYPE: ${reportType}
GENERATED ON: ${new Date().toLocaleString()}

CASE DETAILS
----------------------------------------
Case Number: ${currentCase.caseNumber || "Not available"}
Case Title: ${currentCase.title || "Untitled Case"}
Description: ${currentCase.description || "No description provided"}
Priority: ${currentCase.priority || "Not specified"}
Status: ${currentCase.status || "Not specified"}
Created On: ${
      currentCase.createdAt
        ? new Date(currentCase.createdAt).toLocaleString()
        : "Not available"
    }

INVESTIGATOR DETAILS
----------------------------------------
Investigator: ${investigator || "Not specified"}

INVESTIGATION NOTES
----------------------------------------
${notes || "No additional notes provided."}

AUTOMATED FORENSIC DATA
----------------------------------------
Evidence records, SHA-256 hashes, log events,
correlations and saved findings are included in
the downloadable PDF generated by the backend.

========================================
END OF PREVIEW
`;

    setPreview(report);
    setGenerating(false);
    showMessage("Report preview generated successfully.");
  };

  const downloadReport = async () => {
    if (!currentCase) {
      showMessage("Please select an investigation case.", "error");
      return;
    }

    try {
      setDownloading(true);
      setMessage("");

      const token = localStorage.getItem("forensics_token");

      if (!token) {
        showMessage("Please log in again to download the report.", "error");
        return;
      }

      const response = await api.get(
        `/reports/cases/${selectedCase}/pdf`,
        {
          responseType: "blob",
          headers: {
            Authorization: `Bearer ${token}`,
          },
        }
      );

      const pdfBlob = new Blob([response.data], {
        type: "application/pdf",
      });

      const downloadUrl = window.URL.createObjectURL(pdfBlob);
      const link = document.createElement("a");

      link.href = downloadUrl;
      link.download = `forensic-report-${
        currentCase.caseNumber || "case"
      }.pdf`;

      document.body.appendChild(link);
      link.click();
      link.remove();

      window.URL.revokeObjectURL(downloadUrl);

      showMessage("PDF investigation report downloaded successfully.");
    } catch (error) {
      console.error("PDF download error:", error);
      showMessage(
        "Unable to download PDF. Check your backend server and try again.",
        "error"
      );
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="reports-page">
      <div className="reports-heading">
        <div>
          <span className="reports-eyebrow">CASE DOCUMENTATION</span>
          <h2>Investigation Reports</h2>
          <p>
            Create and download structured forensic investigation reports.
          </p>
        </div>

        <div className="report-heading-icon">▤</div>
      </div>

      <div className="report-summary-grid">
        <div className="report-stat-card">
          <span className="report-stat-icon">▣</span>
          <div>
            <h3>{cases.length}</h3>
            <p>Total Cases</p>
          </div>
        </div>

        <div className="report-stat-card">
          <span className="report-stat-icon">◷</span>
          <div>
            <h3>
              {cases.filter((item) => item.status === "Resolved").length}
            </h3>
            <p>Resolved Cases</p>
          </div>
        </div>

        <div className="report-stat-card">
          <span className="report-stat-icon">▤</span>
          <div>
            <h3>{preview ? "1" : "0"}</h3>
            <p>Generated This Session</p>
          </div>
        </div>
      </div>

      <div className="report-workspace">
        <section className="report-form-card">
          <div className="report-card-heading">
            <div>
              <h3>Create New Report</h3>
              <p>Enter the investigation details below.</p>
            </div>
            <span className="report-step">01</span>
          </div>

          {loading ? (
            <p className="report-message">Loading cases...</p>
          ) : (
            <>
              <label className="report-field">
                Select Investigation Case

                <select
                  value={selectedCase}
                  onChange={(event) => {
                    setSelectedCase(event.target.value);
                    setPreview("");
                    setMessage("");
                  }}
                >
                  <option value="">Choose a case</option>

                  {cases.map((item) => (
                    <option key={item._id} value={item._id}>
                      {item.caseNumber || "Case"} -{" "}
                      {item.title || "Untitled"}
                    </option>
                  ))}
                </select>
              </label>

              <label className="report-field">
                Report Type

                <select
                  value={reportType}
                  onChange={(event) => {
                    setReportType(event.target.value);
                    setPreview("");
                  }}
                >
                  <option>Complete Investigation Report</option>
                  <option>Evidence Summary Report</option>
                  <option>Image Analysis Report</option>
                  <option>Log Analysis Report</option>
                </select>
              </label>

              <label className="report-field">
                Investigator Name

                <input
                  type="text"
                  value={investigator}
                  onChange={(event) =>
                    setInvestigator(event.target.value)
                  }
                  placeholder="Enter investigator name"
                />
              </label>

              <label className="report-field">
                Investigation Notes

                <textarea
                  rows={5}
                  value={notes}
                  onChange={(event) => setNotes(event.target.value)}
                  placeholder="Write important findings, observations and conclusions..."
                />
              </label>

              {message && (
                <p
                  className={`report-message ${
                    messageType === "error"
                      ? "report-error"
                      : "report-success"
                  }`}
                >
                  {message}
                </p>
              )}

              <button
                className="generate-report-button"
                type="button"
                onClick={generateReport}
                disabled={!selectedCase || generating}
              >
                {generating
                  ? "Generating..."
                  : "✦ Generate Report Preview"}
              </button>
            </>
          )}
        </section>

        <section className="report-preview-card">
          <div className="report-card-heading">
            <div>
              <h3>Report Preview</h3>
              <p>Review your report before downloading.</p>
            </div>
            <span className="report-step">02</span>
          </div>

          {preview ? (
            <>
              <pre className="report-preview-content">
                {preview}
              </pre>

              <button
                className="download-report-button"
                type="button"
                onClick={downloadReport}
                disabled={downloading}
              >
                {downloading
                  ? "Preparing PDF..."
                  : "↓ Download Investigation Report (.PDF)"}
              </button>
            </>
          ) : (
            <div className="report-empty-preview">
              <div className="preview-document-icon">▤</div>
              <h4>No Report Generated</h4>
              <p>
                Select a case, enter the details and generate a report
                to see its preview here.
              </p>
            </div>
          )}
        </section>
      </div>

      {message && (
        <div
          className={`report-notice ${
            messageType === "error" ? "report-notice-error" : ""
          }`}
        >
          <span>{messageType === "error" ? "!" : "ⓘ"}</span>
          <p>{message}</p>
        </div>
      )}

      <div className="report-notice">
        <span>ⓘ</span>
        <p>
          The downloadable PDF retrieves case details, evidence metadata,
          SHA-256 hashes, log events, correlations and saved findings from
          the backend. Investigator name, report type and notes are currently
          shown in the preview only; they are not yet included in the PDF.
        </p>
      </div>
    </div>
  );
}

export default Reports;
